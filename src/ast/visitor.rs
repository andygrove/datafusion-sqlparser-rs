/// Calls `f` for every expression in `v`, before its children.
///
/// # Example
///
/// ```
/// # use std::ops::ControlFlow;
/// use sqlparser::ast::visit_expressions;
/// use sqlparser::dialect::Postgres;
/// use sqlparser::parse_sql;
///
/// let statements = parse_sql::<Postgres>("SELECT a FROM foo WHERE x IN (SELECT y FROM bar)").unwrap();
/// let mut visited = vec![];
/// let _ = visit_expressions(&statements, |expr| {
///     visited.push(expr.to_string());
///     ControlFlow::<()>::Continue(())
/// });
/// assert_eq!(visited, ["a", "x IN (SELECT y FROM bar)", "x", "y"]);
/// ```
pub fn visit_expressions<'a, X, V, E, F>(v: &V, f: F) -> ControlFlow<E>
where
    X: AstExt,
    V: Visit<'a, X>,
    F: FnMut(&Expr<'a, X>) -> ControlFlow<E>,
{
    v.visit(&mut ExprVisitor(f))
}

/// Calls `f` with mutable access to every expression in `v`, after its
/// children, so `f` can replace a node that holds the original.
///
/// # Example
///
/// ```
/// # use std::ops::ControlFlow;
/// use sqlparser::ast::{ExprKind, visit_expressions_mut};
/// use sqlparser::dialect::Postgres;
/// use sqlparser::parse_sql;
///
/// let mut statements = parse_sql::<Postgres>("SELECT (SELECT y FROM z LIMIT 9) FROM t LIMIT 3").unwrap();
/// let _ = visit_expressions_mut(&mut statements, |expr| {
///     if let ExprKind::Subquery(query) = &mut expr.kind {
///         query.limit = None;
///     }
///     ControlFlow::<()>::Continue(())
/// });
/// assert_eq!(statements[0].to_string(), "SELECT (SELECT y FROM z) FROM t LIMIT 3");
/// ```
pub fn visit_expressions_mut<'a, X, V, E, F>(v: &mut V, f: F) -> ControlFlow<E>
where
    X: AstExt,
    V: VisitMut<'a, X>,
    F: FnMut(&mut Expr<'a, X>) -> ControlFlow<E>,
{
    v.visit(&mut ExprVisitor(f))
}

struct StatementVisitor<F>(F);

impl<'a, X: AstExt, E, F> Visitor<'a, X> for StatementVisitor<F>
where
    F: FnMut(&Statement<'a, X>) -> ControlFlow<E>,
{
    type Break = E;

    fn pre_visit_statement(&mut self, statement: &Statement<'a, X>) -> ControlFlow<E> {
        self.0(statement)
    }
}

impl<'a, X: AstExt, E, F> VisitorMut<'a, X> for StatementVisitor<F>
where
    F: FnMut(&mut Statement<'a, X>) -> ControlFlow<E>,
{
    type Break = E;

    fn post_visit_statement(&mut self, statement: &mut Statement<'a, X>) -> ControlFlow<E> {
        self.0(statement)
    }
}

/// Calls `f` for every statement in `v`, including nested ones.
pub fn visit_statements<'a, X, V, E, F>(v: &V, f: F) -> ControlFlow<E>
where
    X: AstExt,
    V: Visit<'a, X>,
    F: FnMut(&Statement<'a, X>) -> ControlFlow<E>,
{
    v.visit(&mut StatementVisitor(f))
}

/// Calls `f` with mutable access to every statement in `v`, after its children.
pub fn visit_statements_mut<'a, X, V, E, F>(v: &mut V, f: F) -> ControlFlow<E>
where
    X: AstExt,
    V: VisitMut<'a, X>,
    F: FnMut(&mut Statement<'a, X>) -> ControlFlow<E>,
{
    v.visit(&mut StatementVisitor(f))
}

/// True if `DROP` names tables or views. The other object kinds' names are
/// not relations: `DROP SCHEMA s` drops no table called `s`.
pub(crate) fn drop_names_relations(drop: &DropObject<'_>) -> bool {
    match drop.object_type {
        ObjectType::Table | ObjectType::View | ObjectType::MaterializedView => true,
        ObjectType::Named(kind) => kind.contains("TABLE") || kind.contains("VIEW"),
        ObjectType::Index | ObjectType::Schema | ObjectType::Database | ObjectType::Sequence => {
            false
        }
    }
}

/// True if a `DELETE` names its tables in `multi` instead of `table`. There,
/// `table` repeats the first of the targets.
pub(crate) fn delete_names_many_tables<X: AstExt>(delete: &Delete<'_, X>) -> bool {
    delete.multi.is_some()
}

/// True if what follows `FROM` or `IN` in a `SHOW` names a table: true for
/// `SHOW COLUMNS FROM t`, and not for `SHOW TABLES FROM schema`.
fn show_location_names_table<X: AstExt>(show: &Show<'_, X>) -> bool {
    show.object.iter().any(|word| {
        word.eq_ignore_ascii_case("COLUMNS")
            || word.eq_ignore_ascii_case("FIELDS")
            || word.eq_ignore_ascii_case("INDEX")
            || word.eq_ignore_ascii_case("INDEXES")
            || word.eq_ignore_ascii_case("KEYS")
    })
}

/// True if the name in `SHOW CREATE ...` is a table or view.
fn show_create_names_table<X: AstExt>(show: &Show<'_, X>) -> bool {
    show.object
        .iter()
        .any(|word| word.eq_ignore_ascii_case("TABLE") || word.eq_ignore_ascii_case("VIEW"))
}

impl<'a, X: AstExt> Visit<'a, X> for Show<'a, X> {
    fn visit<V: Visitor<'a, X>>(&self, visitor: &mut V) -> ControlFlow<V::Break> {
        if let Some(name) = &self.name {
            if show_create_names_table(self) {
                visitor.pre_visit_relation(name)?;
                name.visit(visitor)?;
                visitor.post_visit_relation(name)?;
            } else {
                name.visit(visitor)?;
            }
        }
        let mut first_location = show_location_names_table(self);
        for clause in &self.clauses {
            if let ShowClause::Location {
                name: Some(name), ..
            } = clause
                && first_location
            {
                // A second `FROM` is the database, not another table.
                first_location = false;
                visitor.pre_visit_relation(name)?;
                name.visit(visitor)?;
                visitor.post_visit_relation(name)?;
            } else {
                clause.visit(visitor)?;
            }
        }
        ControlFlow::Continue(())
    }
}

impl<'a, X: AstExt> VisitMut<'a, X> for Show<'a, X> {
    fn visit<V: VisitorMut<'a, X>>(&mut self, visitor: &mut V) -> ControlFlow<V::Break> {
        let names_table = show_create_names_table(self);
        let mut first_location = show_location_names_table(self);
        if let Some(name) = &mut self.name {
            if names_table {
                visitor.pre_visit_relation(name)?;
                name.visit(visitor)?;
                visitor.post_visit_relation(name)?;
            } else {
                name.visit(visitor)?;
            }
        }
        for clause in &mut self.clauses {
            if let ShowClause::Location {
                name: Some(name), ..
            } = clause
                && first_location
            {
                first_location = false;
                visitor.pre_visit_relation(name)?;
                name.visit(visitor)?;
                visitor.post_visit_relation(name)?;
            } else {
                clause.visit(visitor)?;
            }
        }
        ControlFlow::Continue(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::dialect::{Builtin, Postgres};
    use crate::parse_sql;

    #[test]
    fn a_walk_breaks_when_a_hook_breaks() {
        struct FirstExpr;
        impl<'a> Visitor<'a, Builtin> for FirstExpr {
            type Break = String;
            fn pre_visit_expr(&mut self, expr: &Expr<'a, Builtin>) -> ControlFlow<String> {
                ControlFlow::Break(expr.to_string())
            }
        }
        let statements = parse_sql::<Postgres>("SELECT 1 + 2, 3").unwrap();
        assert_eq!(
            statements.visit(&mut FirstExpr),
            ControlFlow::Break("1 + 2".to_string())
        );
    }
}
