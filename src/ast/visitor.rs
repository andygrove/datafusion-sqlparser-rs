//! Recursive visitors for the syntax tree. See [`Visitor`] and [`VisitorMut`].
//!
//! Every AST type implements [`Visit`] and [`VisitMut`], generated by the
//! derive macros in `sqlparser_derive`. They take the tree's lifetime and
//! extensions as parameters, because [`Query`] and the other hook arguments
//! are generic over them.

use std::ops::ControlFlow;

use crate::ast::{
    Delete, DropObject, Expr, Ident, Literal, ObjectName, ObjectType, OrderByItem, Query, Select,
    Show, ShowClause, Statement, TableFactor,
};
use crate::dialect::AstExt;

/// A node that a [`Visitor`] can walk. Implemented by `#[derive(Visit)]`.
pub trait Visit<'a, X: AstExt> {
    /// Visits this node, calling the visitor's hooks for it and its children.
    fn visit<V: Visitor<'a, X>>(&self, visitor: &mut V) -> ControlFlow<V::Break>;
}

/// A node that a [`VisitorMut`] can walk. Implemented by `#[derive(VisitMut)]`.
pub trait VisitMut<'a, X: AstExt> {
    /// Visits this node mutably, calling the visitor's hooks for it and its
    /// children.
    fn visit<V: VisitorMut<'a, X>>(&mut self, visitor: &mut V) -> ControlFlow<V::Break>;
}

impl<'a, X: AstExt, T: Visit<'a, X>> Visit<'a, X> for Option<T> {
    fn visit<V: Visitor<'a, X>>(&self, visitor: &mut V) -> ControlFlow<V::Break> {
        if let Some(value) = self {
            value.visit(visitor)?;
        }
        ControlFlow::Continue(())
    }
}

impl<'a, X: AstExt, T: Visit<'a, X>> Visit<'a, X> for Vec<T> {
    fn visit<V: Visitor<'a, X>>(&self, visitor: &mut V) -> ControlFlow<V::Break> {
        for value in self {
            value.visit(visitor)?;
        }
        ControlFlow::Continue(())
    }
}

impl<'a, X: AstExt, T: Visit<'a, X>> Visit<'a, X> for Box<T> {
    fn visit<V: Visitor<'a, X>>(&self, visitor: &mut V) -> ControlFlow<V::Break> {
        T::visit(self, visitor)
    }
}

impl<'a, X: AstExt, T: VisitMut<'a, X>> VisitMut<'a, X> for Option<T> {
    fn visit<V: VisitorMut<'a, X>>(&mut self, visitor: &mut V) -> ControlFlow<V::Break> {
        if let Some(value) = self {
            value.visit(visitor)?;
        }
        ControlFlow::Continue(())
    }
}

impl<'a, X: AstExt, T: VisitMut<'a, X>> VisitMut<'a, X> for Vec<T> {
    fn visit<V: VisitorMut<'a, X>>(&mut self, visitor: &mut V) -> ControlFlow<V::Break> {
        for value in self {
            value.visit(visitor)?;
        }
        ControlFlow::Continue(())
    }
}

impl<'a, X: AstExt, T: VisitMut<'a, X>> VisitMut<'a, X> for Box<T> {
    fn visit<V: VisitorMut<'a, X>>(&mut self, visitor: &mut V) -> ControlFlow<V::Break> {
        T::visit(self, visitor)
    }
}

macro_rules! visit_tuple {
    ($($name:ident),+) => {
        impl<'a, X: AstExt, $($name: Visit<'a, X>),+> Visit<'a, X> for ($($name,)+) {
            #[allow(non_snake_case)]
            fn visit<V: Visitor<'a, X>>(&self, visitor: &mut V) -> ControlFlow<V::Break> {
                let ($($name,)+) = self;
                $($name.visit(visitor)?;)+
                ControlFlow::Continue(())
            }
        }
        impl<'a, X: AstExt, $($name: VisitMut<'a, X>),+> VisitMut<'a, X> for ($($name,)+) {
            #[allow(non_snake_case)]
            fn visit<V: VisitorMut<'a, X>>(&mut self, visitor: &mut V) -> ControlFlow<V::Break> {
                let ($($name,)+) = self;
                $($name.visit(visitor)?;)+
                ControlFlow::Continue(())
            }
        }
    };
}

visit_tuple!(A);
visit_tuple!(A, B);
visit_tuple!(A, B, C);

macro_rules! visit_leaf {
    ($($ty:ty),* $(,)?) => {$(
        impl<'a, X: AstExt> Visit<'a, X> for $ty {
            fn visit<V: Visitor<'a, X>>(&self, _visitor: &mut V) -> ControlFlow<V::Break> {
                ControlFlow::Continue(())
            }
        }
        impl<'a, X: AstExt> VisitMut<'a, X> for $ty {
            fn visit<V: VisitorMut<'a, X>>(&mut self, _visitor: &mut V) -> ControlFlow<V::Break> {
                ControlFlow::Continue(())
            }
        }
    )*};
}

visit_leaf!(bool, char, u8, u32, usize, i64, String);

impl<'a, X: AstExt> Visit<'a, X> for &str {
    fn visit<V: Visitor<'a, X>>(&self, _visitor: &mut V) -> ControlFlow<V::Break> {
        ControlFlow::Continue(())
    }
}

impl<'a, X: AstExt> VisitMut<'a, X> for &str {
    fn visit<V: VisitorMut<'a, X>>(&mut self, _visitor: &mut V) -> ControlFlow<V::Break> {
        ControlFlow::Continue(())
    }
}

impl<'a, X: AstExt, T: Visit<'a, X>, const N: usize> Visit<'a, X> for [T; N] {
    fn visit<V: Visitor<'a, X>>(&self, visitor: &mut V) -> ControlFlow<V::Break> {
        for value in self {
            value.visit(visitor)?;
        }
        ControlFlow::Continue(())
    }
}

impl<'a, X: AstExt, T: VisitMut<'a, X>, const N: usize> VisitMut<'a, X> for [T; N] {
    fn visit<V: VisitorMut<'a, X>>(&mut self, visitor: &mut V) -> ControlFlow<V::Break> {
        for value in self {
            value.visit(visitor)?;
        }
        ControlFlow::Continue(())
    }
}

/// A visitor that walks a syntax tree without changing it.
///
/// `pre_visit_` methods are called before a node's children and `post_visit_`
/// methods after them. Returning [`ControlFlow::Break`] stops the walk.
///
/// `'a` and `X` are the tree's lifetime and extensions, so a visitor usually
/// implements `Visitor<'a, Builtin>` for trees from the built-in dialects.
///
/// See also [`visit_relations`], [`visit_expressions`] and
/// [`visit_statements`], which are shorter when only one kind of node matters.
///
/// # Example
///
/// ```
/// # use std::ops::ControlFlow;
/// use sqlparser::ast::{Expr, ObjectName, Visit, Visitor};
/// use sqlparser::dialect::{Builtin, Postgres};
/// use sqlparser::parse_sql;
///
/// #[derive(Default)]
/// struct V {
///     visited: Vec<String>,
/// }
///
/// impl<'a> Visitor<'a, Builtin> for V {
///     type Break = ();
///
///     fn pre_visit_relation(&mut self, relation: &ObjectName<'a>) -> ControlFlow<()> {
///         self.visited.push(format!("PRE: RELATION: {relation}"));
///         ControlFlow::Continue(())
///     }
///
///     fn pre_visit_expr(&mut self, expr: &Expr<'a, Builtin>) -> ControlFlow<()> {
///         self.visited.push(format!("PRE: EXPR: {expr}"));
///         ControlFlow::Continue(())
///     }
/// }
///
/// let sql = "SELECT a FROM foo WHERE x IN (SELECT y FROM bar)";
/// let statements = parse_sql::<Postgres>(sql).unwrap();
/// let mut visitor = V::default();
/// let _ = statements.visit(&mut visitor);
/// assert_eq!(
///     visitor.visited,
///     [
///         "PRE: EXPR: a",
///         "PRE: RELATION: foo",
///         "PRE: EXPR: x IN (SELECT y FROM bar)",
///         "PRE: EXPR: x",
///         "PRE: EXPR: y",
///         "PRE: RELATION: bar",
///     ]
/// );
/// ```
pub trait Visitor<'a, X: AstExt> {
    /// The value returned when the walk stops early. Keep it small: it is
    /// copied at each level on the way back, and it sits in every visit frame.
    type Break;

    /// Called for any [`Query`] before visiting its children.
    fn pre_visit_query(&mut self, _query: &Query<'a, X>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`Query`] after visiting its children.
    fn post_visit_query(&mut self, _query: &Query<'a, X>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`Select`] before visiting its children.
    fn pre_visit_select(&mut self, _select: &Select<'a, X>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`Select`] after visiting its children.
    fn post_visit_select(&mut self, _select: &Select<'a, X>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called where a table or view is named, before visiting its name's parts.
    fn pre_visit_relation(&mut self, _relation: &ObjectName<'a>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called where a table or view is named, after visiting its name's parts.
    fn post_visit_relation(&mut self, _relation: &ObjectName<'a>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`TableFactor`] before visiting its children.
    fn pre_visit_table_factor(
        &mut self,
        _table_factor: &TableFactor<'a, X>,
    ) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`TableFactor`] after visiting its children.
    fn post_visit_table_factor(
        &mut self,
        _table_factor: &TableFactor<'a, X>,
    ) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`Expr`] before visiting its children.
    fn pre_visit_expr(&mut self, _expr: &Expr<'a, X>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`Expr`] after visiting its children.
    fn post_visit_expr(&mut self, _expr: &Expr<'a, X>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`Statement`] before visiting its children.
    fn pre_visit_statement(&mut self, _statement: &Statement<'a, X>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`Statement`] after visiting its children.
    fn post_visit_statement(&mut self, _statement: &Statement<'a, X>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`Literal`].
    fn pre_visit_value(&mut self, _value: &Literal<'a>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`Literal`].
    fn post_visit_value(&mut self, _value: &Literal<'a>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`Ident`], including the parts of qualified names.
    fn pre_visit_ident(&mut self, _ident: &Ident<'a>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`Ident`].
    fn post_visit_ident(&mut self, _ident: &Ident<'a>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for a query's `ORDER BY`, with its items, before them.
    fn pre_visit_order_by(&mut self, _order_by: &[OrderByItem<'a, X>]) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for a query's `ORDER BY`, with its items, after them.
    fn post_visit_order_by(
        &mut self,
        _order_by: &[OrderByItem<'a, X>],
    ) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`OrderByItem`] before visiting its children.
    fn pre_visit_order_by_expr(&mut self, _item: &OrderByItem<'a, X>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`OrderByItem`] after visiting its children.
    fn post_visit_order_by_expr(&mut self, _item: &OrderByItem<'a, X>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for each `SELECT`'s `GROUP BY` list before visiting it, which
    /// is empty if the query has none.
    fn pre_visit_group_by(&mut self, _group_by: &[Expr<'a, X>]) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for each `SELECT`'s `GROUP BY` list after visiting it.
    fn post_visit_group_by(&mut self, _group_by: &[Expr<'a, X>]) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }
}

/// A visitor that can change a syntax tree as it walks it.
///
/// `pre_visit_` methods are called before a node's children and `post_visit_`
/// methods after them. Returning [`ControlFlow::Break`] stops the walk.
///
/// See also [`visit_relations_mut`], [`visit_expressions_mut`] and
/// [`visit_statements_mut`].
///
/// # Lifetimes limit what can be stored
///
/// Every string in the tree borrows from the SQL text for the tree's lifetime
/// `'a`, and the tree is invariant over `'a`. A replacement written into a node
/// must therefore also live for `'a`: an owned value made inside a hook, such
/// as the result of `format!` or `to_uppercase`, cannot be stored in the tree.
///
/// To rewrite text, borrow it from data that outlives the tree, such as strings
/// prepared before parsing. (Import only `VisitMut`, not `Visit`, to call
/// `.visit` with a mutable visitor; otherwise call `VisitMut::visit` directly.)
///
/// ```
/// # use std::ops::ControlFlow;
/// use sqlparser::ast::{ObjectName, VisitorMut, VisitMut};
/// use sqlparser::dialect::{Builtin, Postgres};
/// use sqlparser::parse_sql;
///
/// struct RenameTables<'r> {
///     from: &'r str,
///     to: &'r str,
/// }
///
/// impl<'a> VisitorMut<'a, Builtin> for RenameTables<'a> {
///     type Break = ();
///
///     fn post_visit_relation(&mut self, relation: &mut ObjectName<'a>) -> ControlFlow<()> {
///         if let [part] = relation.parts.as_mut_slice()
///             && part.text == self.from
///         {
///             part.text = self.to;
///         }
///         ControlFlow::Continue(())
///     }
/// }
///
/// let new_name = String::from("renamed");
/// let sql = "SELECT a FROM foo JOIN bar ON foo.x = bar.x";
/// let mut statements = parse_sql::<Postgres>(sql).unwrap();
/// let mut rename = RenameTables { from: "foo", to: &new_name };
/// let _ = statements.visit(&mut rename);
/// assert_eq!(
///     statements[0].to_string(),
///     "SELECT a FROM renamed JOIN bar ON foo.x = bar.x"
/// );
/// ```
pub trait VisitorMut<'a, X: AstExt> {
    /// The value returned when the walk stops early. Keep it small: it is
    /// copied at each level on the way back, and it sits in every visit frame.
    type Break;

    /// Called for any [`Query`] before visiting its children.
    fn pre_visit_query(&mut self, _query: &mut Query<'a, X>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`Query`] after visiting its children.
    fn post_visit_query(&mut self, _query: &mut Query<'a, X>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`Select`] before visiting its children.
    fn pre_visit_select(&mut self, _select: &mut Select<'a, X>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`Select`] after visiting its children.
    fn post_visit_select(&mut self, _select: &mut Select<'a, X>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called where a table or view is named, before visiting its name's parts.
    fn pre_visit_relation(&mut self, _relation: &mut ObjectName<'a>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called where a table or view is named, after visiting its name's parts.
    fn post_visit_relation(&mut self, _relation: &mut ObjectName<'a>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`TableFactor`] before visiting its children.
    fn pre_visit_table_factor(
        &mut self,
        _table_factor: &mut TableFactor<'a, X>,
    ) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`TableFactor`] after visiting its children.
    fn post_visit_table_factor(
        &mut self,
        _table_factor: &mut TableFactor<'a, X>,
    ) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`Expr`] before visiting its children.
    fn pre_visit_expr(&mut self, _expr: &mut Expr<'a, X>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`Expr`] after visiting its children.
    fn post_visit_expr(&mut self, _expr: &mut Expr<'a, X>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`Statement`] before visiting its children.
    fn pre_visit_statement(
        &mut self,
        _statement: &mut Statement<'a, X>,
    ) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`Statement`] after visiting its children.
    fn post_visit_statement(
        &mut self,
        _statement: &mut Statement<'a, X>,
    ) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`Literal`].
    fn pre_visit_value(&mut self, _value: &mut Literal<'a>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`Literal`].
    fn post_visit_value(&mut self, _value: &mut Literal<'a>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`Ident`], including the parts of qualified names.
    fn pre_visit_ident(&mut self, _ident: &mut Ident<'a>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`Ident`].
    fn post_visit_ident(&mut self, _ident: &mut Ident<'a>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for a query's `ORDER BY`, with its items, before them.
    fn pre_visit_order_by(
        &mut self,
        _order_by: &mut Vec<OrderByItem<'a, X>>,
    ) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for a query's `ORDER BY`, with its items, after them.
    fn post_visit_order_by(
        &mut self,
        _order_by: &mut Vec<OrderByItem<'a, X>>,
    ) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`OrderByItem`] before visiting its children.
    fn pre_visit_order_by_expr(
        &mut self,
        _item: &mut OrderByItem<'a, X>,
    ) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for any [`OrderByItem`] after visiting its children.
    fn post_visit_order_by_expr(
        &mut self,
        _item: &mut OrderByItem<'a, X>,
    ) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for each `SELECT`'s `GROUP BY` list before visiting it, which
    /// is empty if the query has none.
    fn pre_visit_group_by(&mut self, _group_by: &mut Vec<Expr<'a, X>>) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }

    /// Called for each `SELECT`'s `GROUP BY` list after visiting it.
    fn post_visit_group_by(
        &mut self,
        _group_by: &mut Vec<Expr<'a, X>>,
    ) -> ControlFlow<Self::Break> {
        ControlFlow::Continue(())
    }
}

struct RelationVisitor<F>(F);

impl<'a, X: AstExt, E, F> Visitor<'a, X> for RelationVisitor<F>
where
    F: FnMut(&ObjectName<'a>) -> ControlFlow<E>,
{
    type Break = E;

    fn pre_visit_relation(&mut self, relation: &ObjectName<'a>) -> ControlFlow<E> {
        self.0(relation)
    }
}

impl<'a, X: AstExt, E, F> VisitorMut<'a, X> for RelationVisitor<F>
where
    F: FnMut(&mut ObjectName<'a>) -> ControlFlow<E>,
{
    type Break = E;

    fn post_visit_relation(&mut self, relation: &mut ObjectName<'a>) -> ControlFlow<E> {
        self.0(relation)
    }
}

/// Calls `f` for every table or view named in `v`.
///
/// # Example
///
/// ```
/// # use std::ops::ControlFlow;
/// use sqlparser::ast::visit_relations;
/// use sqlparser::dialect::Postgres;
/// use sqlparser::parse_sql;
///
/// let statements = parse_sql::<Postgres>("SELECT a FROM foo WHERE x IN (SELECT y FROM bar)").unwrap();
/// let mut visited = vec![];
/// let _ = visit_relations(&statements, |relation| {
///     visited.push(relation.to_string());
///     ControlFlow::<()>::Continue(())
/// });
/// assert_eq!(visited, ["foo", "bar"]);
/// ```
pub fn visit_relations<'a, X, V, E, F>(v: &V, f: F) -> ControlFlow<E>
where
    X: AstExt,
    V: Visit<'a, X>,
    F: FnMut(&ObjectName<'a>) -> ControlFlow<E>,
{
    v.visit(&mut RelationVisitor(f))
}

/// Calls `f` with mutable access to every table or view named in `v`, after
/// visiting each name.
///
/// See the limit on replacement text at [`VisitorMut`]. A replacement must
/// live as long as the tree does:
///
/// ```
/// # use std::ops::ControlFlow;
/// use sqlparser::ast::visit_relations_mut;
/// use sqlparser::dialect::Postgres;
/// use sqlparser::parse_sql;
///
/// let renamed = String::from("bar");
/// let mut statements = parse_sql::<Postgres>("SELECT a FROM foo").unwrap();
/// let _ = visit_relations_mut(&mut statements, |table| {
///     table.parts[0].text = &renamed;
///     ControlFlow::<()>::Continue(())
/// });
/// assert_eq!(statements[0].to_string(), "SELECT a FROM bar");
/// ```
pub fn visit_relations_mut<'a, X, V, E, F>(v: &mut V, f: F) -> ControlFlow<E>
where
    X: AstExt,
    V: VisitMut<'a, X>,
    F: FnMut(&mut ObjectName<'a>) -> ControlFlow<E>,
{
    v.visit(&mut RelationVisitor(f))
}

