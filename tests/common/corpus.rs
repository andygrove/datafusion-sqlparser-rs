//! The corpus shared by the original crate and this one.
//!
//! Each case is SQL with the original's result in every dialect. The file is
//! generated by `dev/generate_corpus.sh`, and its format is line-based so that
//! changes to it are readable in a diff:
//!
//! ```text
//! %%%% stmt
//! SELECT 1
//! %%%% render ansi mysql
//! SELECT 1
//! %%%% reject hive
//! ```

use std::collections::BTreeMap;

use sqlparser::dialect::{
    BigQuery, ClickHouse, Core, Databricks, Dialect, DuckDb, Hive, MsSql, MySql, Oracle, Postgres,
    Redshift, Snowflake, Spark, Sqlite, Teradata,
};
use sqlparser::{ParseError, parse_expr, parse_sql};
use sqlparser_v1::dialect::dialect_from_str;
use sqlparser_v1::parser::Parser;
use sqlparser_v1::tokenizer::Token;

pub const MARK: &str = "%%%% ";

/// The dialects this crate implements.
pub const V2_DIALECTS: [&str; 15] = [
    "ansi",
    "mysql",
    "postgres",
    "redshift",
    "snowflake",
    "spark",
    "databricks",
    "hive",
    "bigquery",
    "clickhouse",
    "duckdb",
    "mssql",
    "oracle",
    "sqlite",
    "teradata",
];

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    Statement,
    Expr,
}

#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub enum Expected {
    Render(String),
    Reject,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Case {
    pub kind: Kind,
    pub sql: String,
    pub expected: BTreeMap<String, Expected>,
}

impl Kind {
    fn name(self) -> &'static str {
        match self {
            Kind::Statement => "stmt",
            Kind::Expr => "expr",
        }
    }
}

pub fn write_corpus(cases: &[Case]) -> String {
    let mut out = String::new();
    for case in cases {
        out.push_str(&format!("{MARK}{}\n{}\n", case.kind.name(), case.sql));
        let mut groups: BTreeMap<&Expected, Vec<&str>> = BTreeMap::new();
        for (dialect, expected) in &case.expected {
            groups.entry(expected).or_default().push(dialect);
        }
        for (expected, dialects) in groups {
            let dialects = dialects.join(" ");
            match expected {
                Expected::Render(text) => {
                    out.push_str(&format!("{MARK}render {dialects}\n{text}\n"));
                }
                Expected::Reject => out.push_str(&format!("{MARK}reject {dialects}\n")),
            }
        }
    }
    out
}

pub fn parse_corpus(text: &str) -> Vec<Case> {
    let mut cases = Vec::new();
    if text.is_empty() {
        return cases;
    }
    // Splitting on `\n` alone keeps any `\r` in the SQL.
    let mut lines = text
        .strip_suffix('\n')
        .unwrap_or(text)
        .split('\n')
        .peekable();
    while let Some(header) = lines.next() {
        let kind = match header.strip_prefix(MARK) {
            Some("stmt") => Kind::Statement,
            Some("expr") => Kind::Expr,
            _ => panic!("malformed corpus: expected a case header, found {header:?}"),
        };
        let sql = take_body(&mut lines);
        let mut expected = BTreeMap::new();
        while let Some(line) = lines.peek() {
            let rest = line.strip_prefix(MARK).expect("bodies end at a marker");
            if let Some(dialects) = rest.strip_prefix("render ") {
                let dialects = dialects.to_string();
                lines.next();
                let rendered = take_body(&mut lines);
                for dialect in dialects.split(' ') {
                    expected.insert(dialect.to_string(), Expected::Render(rendered.clone()));
                }
            } else if let Some(dialects) = rest.strip_prefix("reject ") {
                for dialect in dialects.split(' ') {
                    expected.insert(dialect.to_string(), Expected::Reject);
                }
                lines.next();
            } else {
                break;
            }
        }
        cases.push(Case {
            kind,
            sql,
            expected,
        });
    }
    cases
}

fn take_body<'t>(lines: &mut std::iter::Peekable<impl Iterator<Item = &'t str>>) -> String {
    let mut body = Vec::new();
    while let Some(line) = lines.peek() {
        if line.starts_with(MARK) {
            break;
        }
        body.push(*line);
        lines.next();
    }
    body.join("\n")
}

/// A stable identifier for a case: the FNV-1a hash of its kind and SQL.
pub fn case_id(kind: Kind, sql: &str) -> String {
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    let bytes = kind.name().bytes().chain([0]).chain(sql.bytes());
    for byte in bytes {
        hash = (hash ^ u64::from(byte)).wrapping_mul(0x0000_0100_0000_01b3);
    }
    format!("{hash:016x}")
}

/// What the original crate does with this SQL in this dialect.
pub fn v1_outcome(kind: Kind, dialect: &str, sql: &str) -> Expected {
    let dialect = dialect_from_str(dialect).unwrap_or_else(|| panic!("unknown {dialect}"));
    let rendered = match kind {
        Kind::Statement => Parser::parse_sql(&*dialect, sql).ok().map(|statements| {
            let rendered: Vec<String> = statements.iter().map(ToString::to_string).collect();
            rendered.join("; ")
        }),
        Kind::Expr => (|| {
            let mut parser = Parser::new(&*dialect).try_with_sql(sql).ok()?;
            let expr = parser.parse_expr().ok()?;
            (parser.peek_token().token == Token::EOF).then(|| expr.to_string())
        })(),
    };
    rendered.map_or(Expected::Reject, Expected::Render)
}

fn parse_with<D: Dialect>(kind: Kind, sql: &str) -> Result<String, ParseError> {
    match kind {
        Kind::Statement => parse_sql::<D>(sql).map(|statements| {
            let rendered: Vec<String> = statements.iter().map(ToString::to_string).collect();
            rendered.join("; ")
        }),
        Kind::Expr => parse_expr::<D>(sql).map(|expr| expr.to_string()),
    }
}

/// This crate's rendering of the SQL in one of [`V2_DIALECTS`].
pub fn v2_result(kind: Kind, dialect: &str, sql: &str) -> Result<String, ParseError> {
    match dialect {
        // The original's ANSI dialect is the nearest thing it has to the core.
        "ansi" => parse_with::<Core>(kind, sql),
        "mysql" => parse_with::<MySql>(kind, sql),
        "postgres" => parse_with::<Postgres>(kind, sql),
        "redshift" => parse_with::<Redshift>(kind, sql),
        "snowflake" => parse_with::<Snowflake>(kind, sql),
        "spark" => parse_with::<Spark>(kind, sql),
        "databricks" => parse_with::<Databricks>(kind, sql),
        "hive" => parse_with::<Hive>(kind, sql),
        "bigquery" => parse_with::<BigQuery>(kind, sql),
        "clickhouse" => parse_with::<ClickHouse>(kind, sql),
        "duckdb" => parse_with::<DuckDb>(kind, sql),
        "mssql" => parse_with::<MsSql>(kind, sql),
        "oracle" => parse_with::<Oracle>(kind, sql),
        "sqlite" => parse_with::<Sqlite>(kind, sql),
        "teradata" => parse_with::<Teradata>(kind, sql),
        other => panic!("this crate does not implement {other}"),
    }
}

/// True if this crate's result is the one the corpus expects.
pub fn v2_matches(expected: &Expected, actual: &Result<String, ParseError>) -> bool {
    match (expected, actual) {
        (Expected::Render(text), Ok(rendered)) => text == rendered,
        (Expected::Reject, Err(_)) => true,
        _ => false,
    }
}
