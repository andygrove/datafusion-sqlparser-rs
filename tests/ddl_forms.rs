// ALTER TABLE, MySQL

#[test]
fn mysql_alter_table_operations_round_trip() {
    for sql in [
        "ALTER TABLE t ALGORITHM = COPY",
        "ALTER TABLE t ALGORITHM INSTANT",
        "ALTER TABLE t LOCK = SHARED",
        "ALTER TABLE t LOCK NONE",
        "ALTER TABLE t AUTO_INCREMENT = 42",
        "ALTER TABLE t AUTO_INCREMENT 42",
        "ALTER TABLE t DROP PRIMARY KEY",
        "ALTER TABLE t DROP FOREIGN KEY c",
        "ALTER TABLE t DROP INDEX i",
        "ALTER TABLE t RENAME AS u",
        "ALTER TABLE t CHANGE COLUMN a desc TEXT NOT NULL",
        "ALTER TABLE t CHANGE COLUMN a b TEXT FIRST",
        "ALTER TABLE t MODIFY COLUMN a TEXT NOT NULL",
        "ALTER TABLE t MODIFY COLUMN a TEXT AFTER b",
        "ALTER TABLE t ADD COLUMN b INT FIRST",
        "ALTER TABLE t ADD COLUMN a TEXT FIRST, ADD COLUMN b INT AFTER c",
        "ALTER TABLE t DROP COLUMN a, ALGORITHM = COPY, RENAME COLUMN b TO c",
    ] {
        round_trips::<MySql>(sql);
        assert!(rejected::<Postgres>(sql), "{sql}");
    }
}

#[test]
fn change_and_modify_check_attributes_like_add() {
    assert!(rejected::<MySql>(
        "ALTER TABLE t ADD a INT UNIQUE DEFERRABLE DEFERRABLE"
    ));
    assert!(rejected::<MySql>(
        "ALTER TABLE t MODIFY a INT UNIQUE DEFERRABLE DEFERRABLE"
    ));
    assert!(rejected::<MySql>(
        "ALTER TABLE t CHANGE a b INT UNIQUE DEFERRABLE DEFERRABLE"
    ));
}

#[test]
fn column_is_written_out_for_change_and_modify() {
    assert_eq!(
        renders::<MySql>("ALTER TABLE t CHANGE a b TEXT"),
        "ALTER TABLE t CHANGE COLUMN a b TEXT"
    );
    assert_eq!(
        renders::<MySql>("ALTER TABLE t MODIFY a TEXT"),
        "ALTER TABLE t MODIFY COLUMN a TEXT"
    );
}

