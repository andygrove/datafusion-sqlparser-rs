//! Generated columns, constraint attributes, sequences, index options and
//! dialect-specific `ALTER TABLE` operations.

use sqlparser::PResult;
use sqlparser::ast::IndexColumn;
use sqlparser::ast::StatementKind;
use sqlparser::dialect::{Builtin, Core, Dialect, MySql, Postgres, Redshift, Snowflake};
use sqlparser::grammar;
use sqlparser::parse_sql;
use sqlparser::parser::Parser;

fn renders<D: Dialect>(sql: &str) -> String {
    let statements = parse_sql::<D>(sql).unwrap_or_else(|e| panic!("{sql}: {e:?}"));
    assert_eq!(statements.len(), 1, "{sql}");
    statements[0].to_string()
}

fn round_trips<D: Dialect>(sql: &str) {
    assert_eq!(renders::<D>(sql), sql);
}

fn round_trips_everywhere(sql: &str) {
    round_trips::<Core>(sql);
    round_trips::<MySql>(sql);
    round_trips::<Postgres>(sql);
    round_trips::<Redshift>(sql);
    round_trips::<Snowflake>(sql);
}

fn rejected<D: Dialect>(sql: &str) -> bool {
    parse_sql::<D>(sql).is_err()
}

// Generated columns

#[test]
fn identity_columns_round_trip() {
    for sql in [
        "CREATE TABLE t (a BIGINT GENERATED ALWAYS AS IDENTITY)",
        "CREATE TABLE t (a BIGINT GENERATED BY DEFAULT AS IDENTITY)",
        "CREATE TABLE t (a BIGINT PRIMARY KEY GENERATED ALWAYS AS IDENTITY, b TEXT)",
        "CREATE TABLE t (a BIGINT GENERATED ALWAYS AS IDENTITY ( INCREMENT 1 MINVALUE 1 ))",
        "CREATE TABLE t (a BIGINT GENERATED ALWAYS AS IDENTITY ( MAXVALUE 20 START WITH 10 CACHE 2 NO CYCLE ))",
    ] {
        round_trips_everywhere(sql);
    }
}

#[test]
fn computed_columns_round_trip() {
    round_trips_everywhere("CREATE TABLE t (a INT, b INT GENERATED ALWAYS AS (a * 2) STORED)");
    for sql in [
        "CREATE TABLE t (a INT, b INT GENERATED ALWAYS AS (a * 2) VIRTUAL)",
        "CREATE TABLE t (a INT, b INT GENERATED ALWAYS AS (a * 2))",
    ] {
        round_trips::<Core>(sql);
        round_trips::<MySql>(sql);
        assert!(rejected::<Postgres>(sql), "{sql}");
    }
}

#[test]
fn generated_needs_its_keywords() {
    assert!(rejected::<Core>("CREATE TABLE t (a INT GENERATED)"));
    assert!(rejected::<Core>("CREATE TABLE t (a INT GENERATED ALWAYS)"));
    assert!(rejected::<Core>(
        "CREATE TABLE t (a INT GENERATED BY AS IDENTITY)"
    ));
}

#[test]
fn only_identity_can_be_added_to_a_column() {
    assert!(rejected::<Postgres>(
        "ALTER TABLE t ALTER COLUMN a ADD GENERATED ALWAYS AS (1 + 1)"
    ));
    assert!(rejected::<Core>(
        "ALTER TABLE t ALTER COLUMN a ADD GENERATED AS (1) VIRTUAL"
    ));
}

#[test]
fn a_column_can_be_altered_to_generated() {
    for sql in [
        "ALTER TABLE t ALTER COLUMN a ADD GENERATED ALWAYS AS IDENTITY",
        "ALTER TABLE t ALTER COLUMN a ADD GENERATED BY DEFAULT AS IDENTITY",
        "ALTER TABLE t ALTER COLUMN a ADD GENERATED AS IDENTITY",
        "ALTER TABLE t ALTER COLUMN a ADD GENERATED AS IDENTITY ( )",
        "ALTER TABLE t ALTER COLUMN a ADD GENERATED AS IDENTITY ( INCREMENT 1 MINVALUE 1 )",
    ] {
        round_trips_everywhere(sql);
    }
}

// Constraint attributes

#[test]
fn column_constraint_attributes_round_trip() {
    for attributes in [
        "DEFERRABLE",
        "NOT DEFERRABLE",
        "DEFERRABLE INITIALLY DEFERRED",
        "INITIALLY IMMEDIATE",
        "ENFORCED",
        "NOT ENFORCED",
        "DEFERRABLE INITIALLY IMMEDIATE NOT ENFORCED",
    ] {
        round_trips_everywhere(&format!("CREATE TABLE t (a INT UNIQUE {attributes})"));
    }
    round_trips_everywhere("CREATE TABLE t (a INT CHECK (a > 0) NOT ENFORCED)");
}

#[test]
fn a_constraint_attribute_can_only_be_given_once() {
    assert!(rejected::<Core>(
        "CREATE TABLE t (a INT UNIQUE DEFERRABLE NOT DEFERRABLE)"
    ));
    assert!(rejected::<Core>(
        "CREATE TABLE t (a INT UNIQUE ENFORCED NOT ENFORCED)"
    ));
    assert!(rejected::<Core>(
        "CREATE TABLE t (a INT, UNIQUE (a) INITIALLY DEFERRED INITIALLY IMMEDIATE)"
    ));
}

#[test]
fn each_constraint_on_a_column_has_its_own_attributes() {
    round_trips_everywhere("CREATE TABLE t (a INT UNIQUE DEFERRABLE REFERENCES u DEFERRABLE)");
    round_trips_everywhere(
        "CREATE TABLE t (a INT UNIQUE NOT DEFERRABLE CHECK (a > 0) NOT DEFERRABLE)",
    );
}

#[test]
fn not_null_is_unaffected() {
    round_trips_everywhere("CREATE TABLE t (a INT NOT NULL)");
    assert!(rejected::<Core>("CREATE TABLE t (a INT NOT)"));
}

#[test]
fn initially_needs_a_mode() {
    assert!(rejected::<Core>("CREATE TABLE t (a INT UNIQUE INITIALLY)"));
}

#[test]
fn table_constraint_attributes_round_trip() {
    for sql in [
        "CREATE TABLE t (a INT, CONSTRAINT c UNIQUE (a) DEFERRABLE INITIALLY DEFERRED)",
        "ALTER TABLE t ADD CONSTRAINT c FOREIGN KEY (a) REFERENCES u (b) NOT VALID",
        "ALTER TABLE t ADD CONSTRAINT c CHECK (a > 0) NO INHERIT",
        "ALTER TABLE t ADD CONSTRAINT c CHECK (a > 0) NO INHERIT NOT VALID",
        "ALTER TABLE t ADD CONSTRAINT c PRIMARY KEY (a) INCLUDE (b, c)",
        "ALTER TABLE t ADD CONSTRAINT c UNIQUE (a) INCLUDE (b)",
        "ALTER TABLE t ADD CONSTRAINT c PRIMARY KEY (a) INCLUDE (b) DEFERRABLE INITIALLY DEFERRED",
        "ALTER TABLE t ADD CONSTRAINT c UNIQUE NULLS DISTINCT (a)",
        "ALTER TABLE t ADD CONSTRAINT c UNIQUE NULLS NOT DISTINCT (a)",
        "ALTER TABLE t ADD CONSTRAINT c PRIMARY KEY USING INDEX i",
        "ALTER TABLE t ADD CONSTRAINT c UNIQUE USING INDEX i NOT DEFERRABLE INITIALLY IMMEDIATE",
        "ALTER TABLE t ADD PRIMARY KEY USING INDEX i",
        "ALTER TABLE t ADD UNIQUE USING INDEX i",
    ] {
        round_trips_everywhere(sql);
    }
}

#[test]
fn foreign_keys_can_say_how_to_match() {
    round_trips_everywhere("CREATE TABLE t (a INT REFERENCES u (b) MATCH FULL ON DELETE CASCADE)");
    round_trips_everywhere("CREATE TABLE t (a INT, FOREIGN KEY (a) REFERENCES u (b) MATCH SIMPLE)");
    round_trips_everywhere("CREATE TABLE t (a INT REFERENCES u MATCH PARTIAL)");
    assert!(rejected::<Core>(
        "CREATE TABLE t (a INT REFERENCES u MATCH)"
    ));
}

// Sequences

#[test]
fn sequences_round_trip() {
    for sql in [
        "CREATE SEQUENCE s",
        "CREATE SEQUENCE IF NOT EXISTS s",
        "CREATE TEMPORARY SEQUENCE s",
        "CREATE SEQUENCE s AS BIGINT INCREMENT 1 MINVALUE 1 MAXVALUE 20 START WITH 10 CACHE 2 NO CYCLE",
        "CREATE SEQUENCE s INCREMENT BY 1",
        "CREATE SEQUENCE s INCREMENT -10 MINVALUE -1000 MAXVALUE 15 START -100",
        "CREATE SEQUENCE s NO MINVALUE NO MAXVALUE CYCLE",
        "CREATE SEQUENCE s OWNED BY a.b",
        "CREATE SEQUENCE s OWNED BY NONE",
        "CREATE SEQUENCE s INCREMENT +10",
    ] {
        round_trips_everywhere(sql);
    }
}

#[test]
fn sequences_cannot_be_replaced() {
    assert!(rejected::<Core>("CREATE OR REPLACE SEQUENCE s"));
}

#[test]
fn signs_in_sequences_are_written_next_to_the_number() {
    assert_eq!(
        renders::<Core>("CREATE SEQUENCE s MINVALUE - 2000 START WITH + 45"),
        "CREATE SEQUENCE s MINVALUE -2000 START WITH +45"
    );
}

#[test]
fn sequence_options_need_values() {
    assert!(rejected::<Core>("CREATE SEQUENCE s INCREMENT"));
    assert!(rejected::<Core>("CREATE SEQUENCE s OWNED a"));
    assert!(rejected::<Core>("CREATE SEQUENCE"));
}

// Indexes

#[test]
fn index_options_round_trip() {
    for sql in [
        "CREATE INDEX i ON t(a) INCLUDE (b, c)",
        "CREATE INDEX i ON t(a) NULLS DISTINCT",
        "CREATE INDEX i ON t(a) NULLS NOT DISTINCT",
        "CREATE INDEX i ON t(a) WHERE b IS NULL",
        "CREATE INDEX i ON t(a, b DESC) USING BTREE",
        "CREATE INDEX i ON t USING BTREE (a) USING HASH",
    ] {
        let sql = sql.replace(" ON t(", " ON t (");
        assert_eq!(renders::<Core>(&sql), sql);
    }
}

#[test]
fn postgres_index_options_round_trip() {
    for sql in [
        "CREATE INDEX CONCURRENTLY IF NOT EXISTS i ON t (a, b)",
        "CREATE INDEX ASYNC i ON t (a)",
        "CREATE UNIQUE INDEX ASYNC i ON t (a)",
    ] {
        assert_eq!(renders::<Postgres>(sql), sql);
    }
}

#[test]
fn mysql_index_options_round_trip() {
    for sql in [
        "CREATE INDEX i ON t (a) USING HASH LOCK = SHARED",
        "CREATE INDEX i ON t (a) USING BTREE LOCK = EXCLUSIVE ALGORITHM = DEFAULT",
    ] {
        assert_eq!(renders::<MySql>(sql), sql);
    }
}

#[test]
fn index_columns_can_have_operator_classes() {
    for sql in [
        "CREATE INDEX i ON t USING GIN (a gin_trgm_ops)",
        "CREATE INDEX i ON t USING GIST (a, f(b, c) gist_trgm_ops)",
        "CREATE INDEX i ON t USING HNSW (a public.vector_cosine_ops)",
    ] {
        round_trips_everywhere(sql);
    }
}

#[test]
fn nulls_order_is_not_an_operator_class() {
    round_trips_everywhere("CREATE INDEX i ON t (a NULLS FIRST)");
}

#[test]
fn index_flag_words_can_name_the_index() {
    round_trips_everywhere("CREATE INDEX async ON t (a)");
}

#[test]
fn concurrently_is_always_the_flag() {
    let statement = parse_sql::<Postgres>("CREATE INDEX CONCURRENTLY ON t (a)")
        .unwrap()
        .remove(0);
    let StatementKind::CreateIndex(index) = statement.kind else {
        panic!("expected CREATE INDEX");
    };
    assert!(index.concurrently);
    assert_eq!(index.name, None);
}

#[test]
fn using_keeps_its_position() {
    round_trips_everywhere("CREATE INDEX i USING BTREE ON t (a)");
    round_trips_everywhere("CREATE INDEX i USING BTREE ON t (a) USING HASH");
    round_trips_everywhere("CREATE INDEX i ON t USING BTREE (a)");
    assert!(rejected::<Core>(
        "CREATE INDEX i USING BTREE ON t USING HASH (a)"
    ));
}

#[test]
fn only_postgres_indexes_take_storage_parameters() {
    round_trips::<Postgres>("CREATE INDEX i ON t USING BLOOM (a) WITH (length = 80, b = 2)");
    round_trips::<Postgres>("CREATE UNIQUE INDEX i ON t (a) WITH (fillfactor = 70, single_param)");
    assert!(rejected::<Core>(
        "CREATE INDEX i ON t (a) WITH (length = 80)"
    ));
}

