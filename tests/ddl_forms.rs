#[derive(Debug, Clone, PartialEq)]
struct DescendingIndexes;

impl Dialect for DescendingIndexes {
    type Ext = Builtin;

    fn parse_index_column<'a>(p: &mut Parser<'a, Self>) -> PResult<IndexColumn<'a, Builtin>> {
        let mut column = grammar::parse_index_column(p)?;
        column.item.asc = Some(false);
        Ok(column)
    }
}

#[test]
fn a_dialect_can_override_index_columns() {
    assert_eq!(
        renders::<DescendingIndexes>("CREATE INDEX i ON t (a)"),
        "CREATE INDEX i ON t (a DESC)"
    );
}
